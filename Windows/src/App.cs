    internal sealed class MainWindow : Window
    {
        private readonly FrameworkElement root;
        private readonly Button maximizeButton;

        public bool AllowClose;
        public event Action ClosedToTray;
        public Func<ContextMenu> SettingsMenu;

        public MainWindow(MixerViewModel model)
        {
            Title = "Audio Mixer";
            Width = 800; Height = 640;
            MinWidth = 680; MinHeight = 460;
            Background = (Brush)Application.Current.Resources["InkBrush"];
            WindowStartupLocation = WindowStartupLocation.CenterScreen;

            WindowChrome chrome = new WindowChrome();
            chrome.CaptionHeight = 58;
            chrome.ResizeBorderThickness = new Thickness(6);
            chrome.GlassFrameThickness = new Thickness(0);
            chrome.CornerRadius = new CornerRadius(0);
            chrome.UseAeroCaptionButtons = false;
            WindowChrome.SetWindowChrome(this, chrome);

            root = (FrameworkElement)Program.LoadXaml("MainWindow.xaml");
            Content = root;
            DataContext = model;

            ((Image)root.FindName("BrandMark")).Source = IconArt.Render(96);
            ((Button)root.FindName("MinimizeButton")).Click += delegate { WindowState = WindowState.Minimized; };
            maximizeButton = (Button)root.FindName("MaximizeButton");
            maximizeButton.Click += delegate { WindowState = WindowState == WindowState.Maximized ? WindowState.Normal : WindowState.Maximized; };
            ((Button)root.FindName("CloseButton")).Click += delegate { Close(); };
            ((Button)root.FindName("EmptyShowSilentButton")).Click += delegate { model.ShowSilentApps = true; };

            Button settings = (Button)root.FindName("SettingsButton");
            settings.Click += delegate
            {
                if (SettingsMenu == null) return;
                ContextMenu menu = SettingsMenu();
                menu.PlacementTarget = settings;
                menu.Placement = PlacementMode.Bottom;
                menu.HorizontalOffset = -208;   // right-align the 230 px menu under the button
                menu.IsOpen = true;
            };

            StateChanged += delegate
            {
                bool maximized = WindowState == WindowState.Maximized;
                // A maximised borderless window hangs over the screen edge by its resize border.
                root.Margin = maximized ? new Thickness(7) : new Thickness(0);
                maximizeButton.Content = maximized ? "" : "";
                maximizeButton.ToolTip = maximized ? "Restore" : "Maximize";
            };
        }

        protected override void OnSourceInitialized(EventArgs e)
        {
            base.OnSourceInitialized(e);
            IntPtr handle = new WindowInteropHelper(this).Handle;
            int dark = 1, round = 2, border = 0x002E2A2A;   // COLORREF 0x00BBGGRR
            Native.DwmSetWindowAttribute(handle, 20, ref dark, 4);     // dark frame
            Native.DwmSetWindowAttribute(handle, 33, ref round, 4);    // rounded corners (Windows 11)
            Native.DwmSetWindowAttribute(handle, 34, ref border, 4);   // hairline border colour
        }

        protected override void OnClosing(CancelEventArgs e)
        {
            if (!AllowClose)
            {
                // Routing keeps working from the tray, like the Mac menu bar item.
                e.Cancel = true;
                Hide();
                if (ClosedToTray != null) ClosedToTray();
            }
            base.OnClosing(e);
        }

        public void ShowFromTray()
        {
            Show();
            if (WindowState == WindowState.Minimized) WindowState = WindowState.Normal;
            Activate();
        }
    }

    internal static class Program
    {
        public const string Version = BuildInfo.Version;
        private const string MutexName = "AudioMixer.SingleInstance.v1";
        private const string ShowEventName = "AudioMixer.Show.v1";

        private static AppSettings settings;
        private static MixerViewModel model;
        private static AudioEngine engine;
        private static MainWindow window;
        private static System.Windows.Forms.NotifyIcon tray;
        private static int peaksPending;

        [STAThread]
        private static int Main(string[] args)
        {
            try
            {
                return Run(args);
            }
            catch (Exception ex)
            {
                DebugLog.Write("fatal: " + ex);
                MessageBox.Show("Audio Mixer could not start.\n\n" + ex.Message + "\n\nDetails: " + DebugLog.Location,
                    "Audio Mixer", MessageBoxButton.OK, MessageBoxImage.Error);
                return 1;
            }
        }

        private static string ArgumentAfter(string[] args, string flag)
        {
            int index = Array.IndexOf(args, flag);
            return index >= 0 && index + 1 < args.Length ? args[index + 1] : null;
        }

        private static int Run(string[] args)
        {
            // Build and QA helpers; none of them start the real app.
            string iconPath = ArgumentAfter(args, "--make-icon");
            if (iconPath != null)
            {
                // Runs unattended inside the build, so fail with an exit code, never a dialog.
                try { File.WriteAllBytes(iconPath, IconArt.IcoBytes()); return 0; }
                catch (Exception ex) { DebugLog.Write("make-icon failed: " + ex); return 2; }
            }
            string selfTestPath = ArgumentAfter(args, "--selftest");
            if (selfTestPath != null)
            {
                // Optional: --probe <pid> <deviceId> moves one process, reads it back, then restores it.
                int probe = Array.IndexOf(args, "--probe");
                uint probePid = probe >= 0 && probe + 2 < args.Length ? uint.Parse(args[probe + 1]) : 0;
                File.WriteAllText(selfTestPath, AudioEngine.SelfTest(probePid, probePid != 0 ? args[probe + 2] : null));
                return 0;
            }
            if (Array.IndexOf(args, "--reset-routes") >= 0)
            {
                // Used by the uninstaller: hand every app back to the system default output.
                string error;
                AudioPolicyConfig policy = AudioPolicyConfig.TryCreate(out error);
                return policy != null && policy.ClearAll() >= 0 ? 0 : 1;
            }
            string screenshotPath = ArgumentAfter(args, "--screenshot");
            bool demo = Array.IndexOf(args, "--demo") >= 0;
            bool test = screenshotPath != null || demo;

            Mutex mutex = null;
            EventWaitHandle showEvent = null;
            if (!test)
            {
                bool first;
                mutex = new Mutex(true, MutexName, out first);
                showEvent = new EventWaitHandle(false, EventResetMode.AutoReset, ShowEventName);
                if (!first)
                {
                    showEvent.Set();   // bring the running copy forward instead of starting a second one
                    return 0;
                }
            }

            Application app = new Application();
            app.ShutdownMode = ShutdownMode.OnExplicitShutdown;
            app.DispatcherUnhandledException += delegate(object sender, DispatcherUnhandledExceptionEventArgs e)
            {
                DebugLog.Write("unhandled: " + e.Exception);
                e.Handled = true;
            };
            app.Resources.MergedDictionaries.Add((ResourceDictionary)LoadXaml("Theme.xaml"));

            settings = new AppSettings();
            if (test) { settings.ReadOnly = true; settings.Assignments.Clear(); settings.ShowSilentApps = false; }
            model = new MixerViewModel(settings);
            model.IconRequested = LoadIcon;
            window = new MainWindow(model);
            window.SettingsMenu = BuildSettingsMenu;
            window.AllowClose = test;   // no tray in demo runs, so closing must really quit
            if (test) window.Closed += delegate { app.Shutdown(); };

            if (demo)
            {
                StartDemo();
            }
            else
            {
                settings.RepairLaunchAtLogin();
                engine = new AudioEngine(settings.Assignments);
                Dispatcher dispatcher = app.Dispatcher;
                engine.SnapshotReady += delegate(Snapshot snapshot)
                {
                    dispatcher.BeginInvoke(new Action(delegate { model.Apply(snapshot); }));
                };
                engine.PeaksReady += delegate(Dictionary<string, float> peaks)
                {
                    if (Interlocked.Exchange(ref peaksPending, 1) == 1) return;
                    dispatcher.BeginInvoke(DispatcherPriority.Background, new Action(delegate
                    {
                        peaksPending = 0;
                        model.ApplyPeaks(peaks);
                    }));
                };
                model.AssignRequested = engine.Assign;
                model.VolumeRequested = engine.SetVolume;
                model.DefaultRequested = engine.SetDefaultOutput;
                Action updateForeground = delegate
                {
                    bool visible = window.IsVisible && window.WindowState != WindowState.Minimized;
                    if (visible && !engine.Foreground) engine.Refresh();
                    engine.Foreground = visible;
                };
                window.IsVisibleChanged += delegate { updateForeground(); };
                window.StateChanged += delegate { updateForeground(); };
                engine.Foreground = false;
                engine.Start();
                DebugLog.Write("launched " + Version + (Array.IndexOf(args, AppSettings.LoginArgument) >= 0 ? " (at login)" : ""));
            }

            if (!test)
            {
                CreateTray();
                window.ClosedToTray += ShowTrayHintOnce;
                Thread listener = new Thread(delegate()
                {
                    while (showEvent.WaitOne())
                    {
                        app.Dispatcher.BeginInvoke(new Action(window.ShowFromTray));
                    }
                });
                listener.IsBackground = true;
                listener.Start();
            }

            bool startHidden = !test && settings.StartHidden && Array.IndexOf(args, AppSettings.LoginArgument) >= 0;
            if (!startHidden) window.Show();

            if (screenshotPath != null)
            {
                string open = ArgumentAfter(args, "--open");
                if (open != null) window.Topmost = true;
                int ticks = 0;
                DispatcherTimer timer = new DispatcherTimer();
                timer.Interval = TimeSpan.FromMilliseconds(1500);
                timer.Tick += delegate
                {
                    ticks++;
                    if (ticks == 1 && open != null) { OpenForScreenshot(open); return; }
                    if (ticks < 2) return;
                    timer.Stop();
                    if (open != null) SaveScreenCapture(screenshotPath); else SaveScreenshot(screenshotPath);
                    Quit();
                };
                timer.Start();
            }

            app.Run();
            GC.KeepAlive(mutex);
            return 0;
        }

        public static object LoadXaml(string name)
        {
            using (Stream stream = Assembly.GetExecutingAssembly().GetManifestResourceStream("AudioMixer." + name))
            {
                if (stream == null) throw new InvalidOperationException("Missing resource " + name);
                return XamlReader.Load(stream);
            }
        }

        private static void Quit()
        {
            if (tray != null)
            {
                tray.Visible = false;
                tray.Dispose();
                tray = null;
            }
            if (engine != null) engine.Stop();
            window.AllowClose = true;
            Application.Current.Shutdown();
        }

        private static void LoadIcon(AppViewModel app)
        {
            if (app.ExePath == null) return;
            ThreadPool.QueueUserWorkItem(delegate
            {
                BitmapSource image = ShellIcon.Load(app.ExePath, 72);
                if (image == null) return;
                Application.Current.Dispatcher.BeginInvoke(new Action(delegate { app.Icon = image; }));
            });
        }

        // ---- Tray icon and menus ----

        private static void CreateTray()
        {
            tray = new System.Windows.Forms.NotifyIcon();
            tray.Text = "Audio Mixer";
            using (MemoryStream stream = new MemoryStream(IconArt.IcoBytes()))
            {
                tray.Icon = new System.Drawing.Icon(stream, System.Windows.Forms.SystemInformation.SmallIconSize);
            }
            tray.Visible = true;
            tray.MouseUp += delegate(object sender, System.Windows.Forms.MouseEventArgs e)
            {
                if (e.Button == System.Windows.Forms.MouseButtons.Left) window.ShowFromTray();
                else if (e.Button == System.Windows.Forms.MouseButtons.Right) OpenTrayMenu();
            };
        }

        private static void ShowTrayHintOnce()
        {
            if (settings.TrayHintShown || tray == null) return;
            settings.TrayHintShown = true;
            settings.Save();
            tray.ShowBalloonTip(4000, "Audio Mixer is still running",
                "Your routes stay active. Right-click the tray icon to quit.", System.Windows.Forms.ToolTipIcon.None);
        }

        private static void OpenTrayMenu()
        {
            OpenTrayMenu(null);
        }

        private static void OpenTrayMenu(UIElement anchor)
        {
            ContextMenu menu = new ContextMenu();
            int listed = 0;
            foreach (AppViewModel app in model.AllApps)
            {
                if (app.IsSystem || !model.RoutingAvailable) continue;
                if (!app.IsPlaying && !settings.ShowSilentApps && !settings.Assignments.ContainsKey(app.Key)) continue;
                menu.Items.Add(BuildAppItem(app));
                listed++;
            }
            if (listed == 0)
            {
                MenuItem none = new MenuItem();
                none.Header = "No apps playing audio";
                none.IsEnabled = false;
                menu.Items.Add(none);
            }
            menu.Items.Add(new Separator());

            MenuItem defaults = new MenuItem();
            defaults.Header = "System default output";
            foreach (DeviceInfo device in model.DeviceList)
            {
                string id = device.Id;
                defaults.Items.Add(Item(device.Name, model.DefaultDeviceId == id, delegate { model.DefaultDeviceId = id; }));
            }
            if (defaults.Items.Count > 0) menu.Items.Add(defaults);

            menu.Items.Add(new Separator());
            AddSettingsItems(menu.Items);
            menu.Items.Add(new Separator());
            menu.Items.Add(Item("Open Audio Mixer", false, delegate { window.ShowFromTray(); }));
            menu.Items.Add(Item("Quit Audio Mixer", false, delegate { Quit(); }));

            menu.Placement = anchor != null ? PlacementMode.Center : PlacementMode.MousePoint;
            menu.PlacementTarget = anchor;
            menu.Opened += delegate
            {
                // A tray menu only closes on an outside click if its window is the foreground one.
                HwndSource source = PresentationSource.FromVisual(menu) as HwndSource;
                if (source != null) Native.SetForegroundWindow(source.Handle);
            };
            menu.IsOpen = true;
        }

        private static MenuItem BuildAppItem(AppViewModel app)
        {
            MenuItem item = new MenuItem();
            string deviceName = app.IsRouted ? model.DeviceName(app.DeviceId) : null;
            item.Header = app.Name + (deviceName != null ? "   →   " + deviceName : "");
            string key = app.Key;
            item.Items.Add(Item("System default", app.DeviceId.Length == 0, delegate { model.Assign(key, ""); }));
            item.Items.Add(new Separator());
            foreach (DeviceInfo device in model.DeviceList)
            {
                string id = device.Id;
                item.Items.Add(Item(device.Name, app.DeviceId == id, delegate { model.Assign(key, id); }));
            }
            return item;
        }

        private static ContextMenu BuildSettingsMenu()
        {
            ContextMenu menu = new ContextMenu();
            AddSettingsItems(menu.Items);
            menu.Items.Add(new Separator());
            MenuItem version = new MenuItem();
            version.Header = "Audio Mixer " + Version;
            version.IsEnabled = false;
            menu.Items.Add(version);
            return menu;
        }

        private static void AddSettingsItems(ItemCollection items)
        {
            bool launch = settings.LaunchAtLogin;
            items.Add(Item("Launch at login", launch, delegate
            {
                string error = settings.SetLaunchAtLogin(!launch);
                model.StatusMessage = error;
            }));
            MenuItem hidden = Item("Start hidden in the tray", settings.StartHidden, delegate
            {
                settings.StartHidden = !settings.StartHidden;
                settings.Save();
            });
            hidden.IsEnabled = launch;
            items.Add(hidden);
            items.Add(Item("Reset all routes", false, delegate
            {
                MessageBoxResult answer = MessageBox.Show(
                    "Send every app back to the system default output?\n\nThis also clears per-app devices set in Windows Settings.",
                    "Audio Mixer", MessageBoxButton.OKCancel, MessageBoxImage.Question, MessageBoxResult.Cancel);
                if (answer != MessageBoxResult.OK) return;
                if (engine != null) engine.ResetAllRoutes();
                model.ClearAssignments();
            }));
        }

        private static MenuItem Item(string header, bool isChecked, Action action)
        {
            MenuItem item = new MenuItem();
            item.Header = header;
            item.IsChecked = isChecked;
            item.Click += delegate { action(); };
            return item;
        }

        // ---- QA helpers ----

        private static void FindAll<T>(DependencyObject parent, List<T> found) where T : DependencyObject
        {
            for (int i = 0; i < VisualTreeHelper.GetChildrenCount(parent); i++)
            {
                DependencyObject child = VisualTreeHelper.GetChild(parent, i);
                T match = child as T;
                if (match != null) found.Add(match);
                FindAll(child, found);
            }
        }

        private static void OpenForScreenshot(string what)
        {
            if (what == "tray") { OpenTrayMenu((UIElement)window.Content); return; }
            if (what == "settings")
            {
                ((Button)((FrameworkElement)window.Content).FindName("SettingsButton")).RaiseEvent(new RoutedEventArgs(ButtonBase.ClickEvent));
                return;
            }
            List<ComboBox> pickers = new List<ComboBox>();
            FindAll((DependencyObject)window.Content, pickers);
            int index = what == "picker" ? 1 : 0;
            if (index < pickers.Count) pickers[index].IsDropDownOpen = true;
        }

        /// Copies the real screen so separate popup windows (menus, pickers) are included.
        private static void SaveScreenCapture(string path)
        {
            FrameworkElement content = (FrameworkElement)window.Content;
            Point topLeft = content.PointToScreen(new Point(0, 0));
            Point bottomRight = content.PointToScreen(new Point(content.ActualWidth, content.ActualHeight));
            int width = (int)(bottomRight.X - topLeft.X), height = (int)(bottomRight.Y - topLeft.Y);
            using (System.Drawing.Bitmap bitmap = new System.Drawing.Bitmap(width, height))
            {
                using (System.Drawing.Graphics graphics = System.Drawing.Graphics.FromImage(bitmap))
                {
                    graphics.CopyFromScreen((int)topLeft.X, (int)topLeft.Y, 0, 0, new System.Drawing.Size(width, height));
                }
                bitmap.Save(path, System.Drawing.Imaging.ImageFormat.Png);
            }
        }

        private static void SaveScreenshot(string path)
        {
            FrameworkElement content = (FrameworkElement)window.Content;
            const double scale = 1.5;
            RenderTargetBitmap bitmap = new RenderTargetBitmap(
                (int)Math.Ceiling(content.ActualWidth * scale), (int)Math.Ceiling(content.ActualHeight * scale),
                96 * scale, 96 * scale, PixelFormats.Pbgra32);
            bitmap.Render(content);
            File.WriteAllBytes(path, IconArt.Png(bitmap));
        }

        /// Fake devices and apps so the window can be reviewed without real audio.
        private static void StartDemo()
        {
            Snapshot snapshot = new Snapshot();
            snapshot.RoutingAvailable = true;
            string[] deviceNames = { "Headset (HyperX Cloud II Wireless)", "LG ULTRAGEAR (NVIDIA High Definition Audio)", "Maonocaster E2 (USB Audio)", "Speakers (Realtek(R) Audio)" };
            foreach (string name in deviceNames)
            {
                DeviceInfo device = new DeviceInfo();
                device.Id = name; device.Name = name;
                snapshot.Devices.Add(device);
            }
            snapshot.DefaultId = deviceNames[3];

            string programs = Environment.GetFolderPath(Environment.SpecialFolder.ProgramFiles);
            string windows = Environment.GetFolderPath(Environment.SpecialFolder.Windows);
            string[][] apps =
            {
                new[] { "Discord", Path.Combine(windows, "explorer.exe"), "1", "0.8", deviceNames[0] },
                new[] { "Google Chrome", Path.Combine(programs, @"Google\Chrome\Application\chrome.exe"), "1", "1", "" },
                new[] { "Spotify", Path.Combine(windows, @"System32\mspaint.exe"), "1", "0.65", deviceNames[2] },
                new[] { "System sounds", null, "0", "0.4", "" },
                new[] { "Visual Studio Code", Path.Combine(windows, "notepad.exe"), "0", "1", deviceNames[1] },
            };
            if (Array.IndexOf(Environment.GetCommandLineArgs(), "--demo-empty") < 0)
            {
                foreach (string[] entry in apps)
                {
                    AppInfo info = new AppInfo();
                    info.Key = entry[0].ToLowerInvariant();
                    info.Name = entry[0];
                    info.ExePath = entry[1] != null && File.Exists(entry[1]) ? entry[1] : null;
                    info.IsSystem = entry[1] == null;
                    info.IsPlaying = entry[2] == "1";
                    info.Volume = float.Parse(entry[3], System.Globalization.CultureInfo.InvariantCulture);
                    if (entry[4].Length > 0) settings.Assignments[info.Key] = entry[4];
                    snapshot.Apps.Add(info);
                }
            }
            settings.ShowSilentApps = Array.IndexOf(Environment.GetCommandLineArgs(), "--demo-silent") >= 0;
            model.Apply(snapshot);

            Random random = new Random(7);
            DispatcherTimer timer = new DispatcherTimer();
            timer.Interval = TimeSpan.FromMilliseconds(50);
            timer.Tick += delegate
            {
                Dictionary<string, float> peaks = new Dictionary<string, float>();
                foreach (AppViewModel app in model.AllApps)
                {
                    if (app.IsPlaying) peaks[app.Key] = (float)(0.05 + random.NextDouble() * 0.6);
                }
                model.ApplyPeaks(peaks);
            };
            timer.Start();
        }
